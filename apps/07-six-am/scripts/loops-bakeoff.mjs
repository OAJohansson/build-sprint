// AI loops bake-off (S4, A10): the SAME 5 bass-loop prompts on each provider, files and a JSON
// manifest written OUTSIDE the repo for data-evals to grade (key, tempo, loop, quality). This
// script doesn't judge anything. Never prints a key.
//
//   node scripts/loops-bakeoff.mjs --out /path/outside/repo [--only 1,2] [--variants stability:stable-audio-2.5,lyria:lyria-3-clip-preview]
//
// Cost: Stable Audio 2.5 / 3.0 = 8 credits ($0.08) per loop, Lyria 3 Clip = $0.04 per loop, so the
// default three variants × 5 prompts ≈ $1.00. Stops a variant after 2 failures in a row, and the
// whole run if the estimate passes $2.50.
// Runs the app's own adapters and prompt builder directly (Node type stripping; Node ≥ 22.18).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bassLoopRequest, loopSeconds } from "../src/lib/ai-loops/prompt.ts";
import { lyriaAdapter } from "../src/lib/server/ai-loops/lyria.ts";
import { stabilityAdapter } from "../src/lib/server/ai-loops/stability.ts";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const envFile = here("../.env.local");
const fromFile = (name) => {
  if (!existsSync(envFile)) return "";
  const line = readFileSync(envFile, "utf8").split("\n").find((l) => l.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1).trim().replace(/^["']|["']$/g, "") : "";
};
const keys = { stability: process.env.STABILITY_API_KEY ?? fromFile("STABILITY_API_KEY"), lyria: process.env.GEMINI_API_KEY ?? fromFile("GEMINI_API_KEY") };

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const out = arg("out");
if (!out) {
  console.error("Pass --out <dir> (outside the repo).");
  process.exit(1);
}
const repoRoot = resolve(here("../../.."));
if (resolve(out).startsWith(repoRoot)) {
  console.error("--out must be outside the repo: generated audio is never committed.");
  process.exit(1);
}
const only = arg("only")?.split(",").map(Number);
const variants = (arg("variants") ?? "stability:stable-audio-2.5,lyria:lyria-3-clip-preview,stability:stable-audio-3").split(",").map((v) => {
  const [provider, model] = v.split(":");
  return { provider, model, dir: model === "stable-audio-3" ? "stability-3" : provider };
});
const MAX_USD = 2.5;

// The 5 prompts: requested values are fixed here before any result is seen (like L35).
const SEED = 42;
const CASES = [
  { n: 1, bpm: 120, key: "A", scale: "minor", bars: 8, genres: [{ style: "Electronic---Deep House", p: 0.6 }] },
  { n: 2, bpm: 124, key: "F", scale: "minor", bars: 8, genres: [{ style: "Electronic---Tech House", p: 0.55 }] },
  { n: 3, bpm: 126, key: "C", scale: "major", bars: 4, genres: [{ style: "Electronic---Disco", p: 0.5 }, { style: "Electronic---House", p: 0.3 }] },
  { n: 4, bpm: 128, key: "D#", scale: "minor", bars: 8, genres: [{ style: "Electronic---Techno", p: 0.6 }] },
  { n: 5, bpm: 145, key: "G", scale: "minor", bars: 8, genres: [{ style: "Electronic---Trance", p: 0.5 }] },
].filter((c) => !only || only.includes(c.n));

const ext = (mime) => (/wav/.test(mime) ? "wav" : /mpeg|mp3/.test(mime) ? "mp3" : "bin");

async function stabilityBalance() {
  // Free account call; the credits before and after give the real charge for X5.
  if (!keys.stability) return null;
  try {
    const res = await fetch("https://api.stability.ai/v1/user/balance", { headers: { authorization: `Bearer ${keys.stability}` } });
    if (!res.ok) return null;
    return (await res.json()).credits ?? null;
  } catch {
    return null;
  }
}

mkdirSync(out, { recursive: true });
const manifest = {
  ranAt: new Date().toISOString(),
  note: "Generated by apps/07-six-am/scripts/loops-bakeoff.mjs. Requested values are what was asked; nothing here is graded.",
  seed: SEED,
  stabilityCreditsBefore: await stabilityBalance(),
  stabilityCreditsAfter: null,
  items: [],
  totals: {},
};
let spent = 0;

for (const v of variants) {
  if (!keys[v.provider]) {
    console.log(`Skip ${v.provider}: no key.`);
    continue;
  }
  const adapter = v.provider === "lyria" ? lyriaAdapter(v.model, 120_000) : stabilityAdapter(v.model, 120_000);
  mkdirSync(join(out, v.dir), { recursive: true });
  let failsInRow = 0;
  for (const c of CASES) {
    if (spent >= MAX_USD) {
      console.log(`Stop: estimate $${spent.toFixed(2)} reached the $${MAX_USD} limit.`);
      break;
    }
    const req = bassLoopRequest(c, c.bars, v.provider === "stability" ? SEED : undefined);
    const base = {
      n: c.n, provider: v.provider, model: v.model, prompt: req.prompt,
      requested: { bpm: req.bpm, key: req.key, scale: req.scale, bars: req.bars, seconds: loopSeconds(req.bpm, req.bars), seed: req.seed ?? null },
    };
    process.stdout.write(`${v.dir} #${c.n} ${req.bpm} BPM ${req.key} ${req.scale} ${req.bars} bars … `);
    try {
      const r = await adapter.generate(req, keys[v.provider]);
      const file = join(v.dir, `${String(c.n).padStart(2, "0")}.${ext(r.mime)}`);
      writeFileSync(join(out, file), r.audio);
      spent += r.costUsd;
      failsInRow = 0;
      manifest.items.push({ ...base, file, mime: r.mime, bytes: r.audio.byteLength, secondsTaken: r.seconds, costUsd: r.costUsd, requestedSeconds: r.requestedSeconds, meta: r.meta });
      console.log(`${r.seconds}s, $${r.costUsd.toFixed(2)}, ${(r.audio.byteLength / 1024).toFixed(0)} KB`);
    } catch (e) {
      failsInRow++;
      manifest.items.push({ ...base, error: e instanceof Error ? e.message : String(e), status: e?.status ?? null });
      console.log(`FAILED: ${e instanceof Error ? e.message : e}`);
      if (failsInRow >= 2) {
        console.log(`Stop ${v.dir}: 2 failures in a row.`);
        break;
      }
    }
  }
}

// The balance lags the last charge by a few seconds (seen on 25 Oct): wait before reading it.
await new Promise((r) => setTimeout(r, 20_000));
manifest.stabilityCreditsAfter = await stabilityBalance();
for (const v of variants) {
  const ok = manifest.items.filter((i) => i.model === v.model && !i.error);
  manifest.totals[v.dir] = {
    model: v.model,
    loops: ok.length,
    failed: manifest.items.filter((i) => i.model === v.model && i.error).length,
    costUsd: Math.round(ok.reduce((s, i) => s + i.costUsd, 0) * 100) / 100,
    medianSecondsTaken: ok.length ? ok.map((i) => i.secondsTaken).sort((a, b) => a - b)[Math.floor(ok.length / 2)] : null,
  };
}
manifest.totals.allUsd = Math.round(spent * 100) / 100;
if (manifest.stabilityCreditsBefore != null && manifest.stabilityCreditsAfter != null) {
  manifest.totals.stabilityCreditsUsed = Math.round((manifest.stabilityCreditsBefore - manifest.stabilityCreditsAfter) * 100) / 100;
}
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2));
console.log(`Estimated spend $${spent.toFixed(2)}. Manifest: ${join(out, "manifest.json")}`);
