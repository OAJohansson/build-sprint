// Imports the researched, sourced content into the app's schema. Re-runnable: edit the source, not the output.
//   pnpm -F 11-meander content
// Reads  docs/products/11-meander/content/full.json   (schema: sources.md in that folder)
// Writes src/content/schools.json, thinkers.json, links.json  (then run `pnpm -F 11-meander positions`
// if schools or links changed). Every school, theme, question, thinker, key idea, prompt and link keeps its
// `sources`. Fails loudly on anything the app can't resolve (unknown neighbour, theme thinker not in the school).
import fs from "node:fs";

const SRC = new URL("../../../docs/products/11-meander/content/full.json", import.meta.url);
const OUT = new URL("../src/content/", import.meta.url);
const full = JSON.parse(fs.readFileSync(SRC, "utf8"));
const problems = [];

const slug = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/\(.*?\)/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const src = (list) => (list ?? []).map((s) => ({ url: s.url, ...(s.section ? { section: s.section } : {}), ...(s.quote ? { quote: s.quote } : {}) }));

// The short name used in inline rows ("Kierkegaard · Sartre"). Default: the last word; these read better.
const SHORT = {
  "Thales of Miletus": "Thales", "Pythagoras of Samos": "Pythagoras", "Heraclitus of Ephesus": "Heraclitus",
  "Parmenides of Elea": "Parmenides", "Zeno of Citium": "Zeno", "Chrysippus of Soli": "Chrysippus",
  "Alexander of Aphrodisias": "Alexander", "Augustine of Hippo": "Augustine", "Sextus Empiricus": "Sextus",
  "Marcus Aurelius": "Marcus Aurelius", "Pseudo-Dionysius the Areopagite": "Pseudo-Dionysius",
  "William of Ockham": "Ockham", "John Duns Scotus": "Duns Scotus", "Francesco Petrarca (Petrarch)": "Petrarch",
  "Giovanni Pico della Mirandola": "Pico", "Harriet Taylor Mill": "Taylor Mill",
};
const shortName = (name) => SHORT[name] ?? name.replace(/\s*\(.*?\)\s*/g, " ").trim().split(/\s+/).pop();
// A short date for the line under the title: date_range without its asides in brackets and up to the first ";",
// unless the source gives `short_dates`.
const shortDates = (s) => (s.short_dates ?? (s.date_range ?? "").replace(/\s*\([^)]*\)/g, "").split(";")[0]).trim();

const schools = [], thinkers = [], links = [];
const ids = new Set(full.map((s) => s.id));
for (const s of full) {
  const tid = (name) => `${s.id}/${slug(name)}`;
  const names = new Set(s.thinkers.map((t) => t.name));
  for (const t of s.thinkers) {
    thinkers.push({
      id: tid(t.name), name: t.name, short: shortName(t.name), dates: t.dates ?? "", school: s.id,
      summary: t.summary ?? "", ideas: (t.key_ideas ?? []).map((k) => k.text),
      ideaSources: (t.key_ideas ?? []).map((k) => src(k.sources)),
      ...(t.study_prompt?.text ? { prompt: t.study_prompt.text, promptSources: src(t.study_prompt.sources) } : {}),
      sources: src(t.sources), sample: false,
    });
  }
  schools.push({
    id: s.id, name: s.name, dates: shortDates(s), dateRange: s.date_range ?? "", era: s.era ?? "",
    description: s.description ?? "", ...(s.tagline ? { tagline: s.tagline } : {}), debatable: s.debatable ?? null,
    questions: (s.questions ?? []).map((q) => q.text),
    questionSources: (s.questions ?? []).map((q) => src(q.sources)),
    themes: (s.themes ?? []).map((th) => ({
      name: th.title, text: th.text ?? "",
      thinkers: (th.thinkers ?? []).filter((n) => {
        if (!names.has(n)) problems.push(`${s.id}: theme "${th.title}" names "${n}", who is not one of its thinkers`);
        return names.has(n);
      }).map(tid),
      sources: src(th.sources),
    })),
    reactedAgainst: s.reacted_against ? { text: s.reacted_against.text, sources: src(s.reacted_against.sources) } : null,
    thinkers: s.thinkers.map((t) => tid(t.name)),
    sources: src(s.sources), sample: false,
  });
  // Each link appears at both ends in full.json; take it once, from the school that is its "from" (direction "out").
  // full.json reads from → to as "from built on / pushed against to"; the app stores from = older, to = newer.
  for (const l of s.links ?? []) {
    if (l.direction !== "out") continue;
    if (!ids.has(l.neighbour)) { problems.push(`${s.id}: link to unknown school "${l.neighbour}"`); continue; }
    const type = { built_on: "built", pushed_against: "against", built_on_then_pushed_against: "built-then-against" }[l.kind];
    if (!type) { problems.push(`${s.id} → ${l.neighbour}: unknown link kind "${l.kind}"`); continue; }
    links.push({ from: l.neighbour, to: s.id, type, label: l.label ?? "", reason: l.reason ?? "", sources: src(l.sources), sample: false });
  }
}
const tids = thinkers.map((t) => t.id);
for (const id of tids) if (tids.indexOf(id) !== tids.lastIndexOf(id)) problems.push(`duplicate thinker id ${id}`);
if (problems.length) { console.error("import-content: cannot import\n  " + problems.join("\n  ")); process.exit(1); }

const note = "Generated by scripts/import-content.mjs from docs/products/11-meander/content/full.json. Do not edit by hand; fix the source and re-run `pnpm -F 11-meander content`.";
const write = (file, key, items) => fs.writeFileSync(new URL(file, OUT), JSON.stringify({ sample: false, note, [key]: items }, null, 2) + "\n");
write("schools.json", "schools", schools);
write("thinkers.json", "thinkers", thinkers);
write("links.json", "links", links);
const unsourced = [...schools, ...thinkers, ...links, ...schools.flatMap((s) => s.themes)].filter((x) => !x.sources.length).length;
console.log(`content: ${schools.length} schools, ${thinkers.length} thinkers, ${links.length} links; ${unsourced} items without sources`);
console.log("now run: pnpm -F 11-meander positions (if schools or links changed)");
