// Copies the sourced places and spans into the app (L32's When / Where lines). Re-runnable.
//   pnpm -F 11-meander places
// Reads  docs/products/11-meander/content/places.json  ({ "<school-id>": { places: [..], span: "1843–1949" | null, sources: [..] } })
// Writes src/content/places.json with only what the app shows ({ places, span }). With no source file it writes {},
// and the first page shows When from the school's dates and no Where line.
// Also writes src/content/eras.json: numeric years per school for the timeline (#41), from the hand-read table below.
import fs from "node:fs";

const SRC = new URL("../../../docs/products/11-meander/content/places.json", import.meta.url);
const OUT = new URL("../src/content/places.json", import.meta.url);
// shortcut: these years are read by hand from each school's sourced `span` (places.json), not sourced separately; replace them with sourced start and end years if the timeline needs to be exact.
// from / to are years, BCE negative. to: "present" is resolved to the current year in the app. roots: an earlier lead-in
// the span names ("roots in the 1840s"), drawn faint. open: the span gives no end ("from 335 BCE", "and later"), so the
// bar fades out instead of stopping. living: a tradition still alive today; from–to is its classical period (solid)
// and a faint tail runs on to the present. A school missing here is left off the timeline, not an error.
const ERAS = {
  presocratics: { from: -600, to: -400 }, //          6th–5th century BCE
  "socrates-plato": { from: -430, to: -350 }, //      late 5th–mid 4th century BCE
  aristotle: { from: -335, to: 200, open: true }, //  from 335 BCE (to Alexander of Aphrodisias, c. 200 CE, its last listed thinker)
  epicureanism: { from: -307, to: -1, open: true }, // 307/6 BCE–1st century BCE and later
  stoicism: { from: -300, to: 200 }, //               c. 300 BCE–2nd century CE
  skepticism: { from: -300, to: 200 }, //             3rd century BCE–2nd century CE
  neoplatonism: { from: 250, to: 650 }, //            mid-3rd–mid-7th century CE
  patristic: { from: 200, to: 600 }, //               3rd–6th century CE
  scholasticism: { from: 1100, to: 1700 }, //         12th century–late 17th century
  renaissance: { from: 1350, to: 1620 }, //           mid-14th–early 17th century
  rationalism: { from: 1600, to: 1800 }, //           17th–18th centuries
  empiricism: { from: 1600, to: 1800 }, //            17th–18th centuries
  enlightenment: { from: 1700, to: 1800 }, //         18th century
  "german-idealism": { from: 1780, to: 1850 }, //     1780s–1840s
  utilitarianism: { from: 1789, to: "present" }, //   1789–present
  marxism: { from: 1840, to: "present" }, //          1840s–present
  existentialism: { from: 1940, to: 1970, roots: 1840 }, // mid-20th century (roots in the 1840s)
  pragmatism: { from: 1870, to: "present" }, //       c. 1870–present
  phenomenology: { from: 1900, to: "present" }, //    1900–present
  analytic: { from: 1900, to: "present" }, //         c. 1900–present
  "critical-theory": { from: 1923, to: "present" }, // 1923–present
  "post-structuralism": { from: 1960, to: "present", open: true }, // from the 1960s
  "feminist-philosophy": { from: 1970, to: "present" }, // 1970s–present
  // The Eastern schools (#42): classical period solid, then living today.
  "buddhist-philosophy": { from: -500, to: 1100, living: true }, // 5th century BCE – 11th century CE in India; living today
  vedanta: { from: -700, to: 1200, living: true }, //  c. 700 BCE (early Upaniṣads) – 12th century CE, and living today
  confucianism: { from: -600, to: -200, living: true }, // 6th–3rd century BCE (classical period); still influential today
  daoism: { from: -500, to: -200, living: true }, //   5th–3rd century BCE; Neo-Daoism from the 3rd century CE; living today as a religion
};
const ERAS_OUT = new URL("../src/content/eras.json", import.meta.url);
{
  const out = {}, bad = [];
  for (const [id, e] of Object.entries(ERAS)) {
    const to = e.to === "present" ? Infinity : e.to;
    if (!Number.isInteger(e.from) || !(to >= e.from) || (e.roots != null && !(e.roots < e.from))) bad.push(`${id}: years out of order`);
    out[id] = e;
  }
  if (bad.length) { console.error("import-places: eras table\n  " + bad.join("\n  ")); process.exit(1); }
  fs.writeFileSync(ERAS_OUT, JSON.stringify({ note: "Generated by scripts/import-places.mjs from its hand-read ERAS table. Do not edit by hand.", eras: out }, null, 2) + "\n");
  console.log(`import-places: ${Object.keys(out).length} school spans for the timeline`);
}

const schools = new Set(JSON.parse(fs.readFileSync(new URL("../src/content/schools.json", import.meta.url), "utf8")).schools.map((s) => s.id));

if (!fs.existsSync(SRC)) {
  fs.writeFileSync(OUT, "{}\n");
  console.log("import-places: no places.json yet; wrote {}");
  process.exit(0);
}
const src = JSON.parse(fs.readFileSync(SRC, "utf8"));
const out = {}, problems = [];
for (const [id, v] of Object.entries(src)) {
  if (!schools.has(id)) { problems.push(`unknown school "${id}"`); continue; }
  const places = Array.isArray(v?.places) ? v.places.filter((p) => typeof p === "string" && p.trim()).map((p) => p.trim()) : [];
  const span = typeof v?.span === "string" && v.span.trim() ? v.span.trim() : null;
  if (v?.places != null && !Array.isArray(v.places)) problems.push(`${id}: places is not a list`);
  out[id] = { places, span };
}
if (problems.length) { console.error("import-places: cannot import\n  " + problems.join("\n  ")); process.exit(1); }
fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(`import-places: ${Object.keys(out).length} schools`);
